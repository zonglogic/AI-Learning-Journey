'''
    该案例演示了语法错误和异常
        语法错误:程序不会执行
        异常:语法是正确的,在运行它的时候,发现的错误称为异常
            如果不对程序运行的过程中,发生的异常进行处理,程序默认的处理方式是将异常打印到控制台
            程序也会种植,异常后面的代码不会被执行
    异常处理
        异常处理的目的,不是为了规避异常的发生,而是当程序发生异常了,提供对异常的处理方案,让程序不终止,可以继续向下执行
        基本语法
            try:
                可能发生异常的语法
            except:
                异常处理的代码
        说明:
            如果发生了异常,那么try后面的代码将不再被执行,直接执行except块中对异常进行处理的代码
            如果没有发生异常,那么except块中的代码将不会被执行,直接执行异常处理后面的代码
'''

try:
    res=3/0
    print(res)
except:
    print("程序出现了异常")

print("end")





























